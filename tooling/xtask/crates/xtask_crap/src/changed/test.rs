use super::*;

#[test]
fn a_complete_listing_names_its_paths() {
    let listing = read_listing("complete\ncrates/a/src/lib.rs\nREADME.md\n");

    assert_eq!(
        listing,
        Listing::Complete(vec![
            "crates/a/src/lib.rs".to_owned(),
            "README.md".to_owned()
        ])
    );
}

#[test]
fn a_partial_or_unavailable_listing_leaves_the_diff_to_decide() {
    assert_eq!(
        read_listing("partial\ncrates/a/src/lib.rs\n"),
        Listing::Incomplete
    );
    assert_eq!(read_listing("unavailable\n"), Listing::Incomplete);
    assert_eq!(read_listing(""), Listing::Incomplete);
}

#[test]
fn rust_source_is_scored() {
    assert!(is_scored("crates/factory_engine/src/domain/checks.rs"));
    assert!(is_scored("crates/a/src/main.rs"));
    assert!(is_scored("services/factory_service/src/gate_replay.rs"));
    assert!(is_scored("services/factory_service/src/bin/tool.rs"));
}

#[test]
fn tests_generated_code_migrations_and_startup_code_are_not_scored() {
    assert!(!is_scored("crates/a/tests/flow.rs"));
    assert!(!is_scored("crates/a/src/domain/test.rs"));
    assert!(!is_scored("crates/a/src/domain/tests.rs"));
    assert!(!is_scored("crates/a/src/domain/test/fakes.rs"));
    assert!(!is_scored("crates/a/benches/speed.rs"));
    assert!(!is_scored("crates/a/examples/demo.rs"));
    assert!(!is_scored("crates/a/build.rs"));
    assert!(!is_scored("crates/a/src/generated/schema.rs"));
    assert!(!is_scored(
        "crates/macro_db_client/migrations/20250101_add.rs"
    ));
    assert!(!is_scored("crates/a/.sqlx/query-1.json"));
    assert!(!is_scored("vendor/patched/src/lib.rs"));
    assert!(!is_scored("services/factory_service/src/main.rs"));
    assert!(!is_scored("crates/a/src/lib.ts"));
    assert!(!is_scored("README.md"));
}

#[test]
fn a_marker_near_the_top_says_a_file_is_generated() {
    assert!(is_generated("// @generated by build.rs\nfn a() {}\n"));
    assert!(!is_generated("fn a() {}\n"));
    assert!(!is_generated("\n\n\n\n\n// @generated\n"));
}
