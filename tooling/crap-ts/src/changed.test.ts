import { describe, expect, it } from 'bun:test';
import { isGenerated, isScored, readListing, testFolders } from './changed';

describe('readListing', () => {
  it('lists the paths of a complete listing', () => {
    expect(
      readListing('complete\napps/web/src/a.ts\n\napps/web/b.tsx\n')
    ).toEqual(['apps/web/src/a.ts', 'apps/web/b.tsx']);
  });

  it('leaves a partial, unavailable or empty listing to the diff', () => {
    expect(readListing('partial\napps/web/src/a.ts\n')).toBeNull();
    expect(readListing('unavailable\n')).toBeNull();
    expect(readListing('')).toBeNull();
  });
});

describe('isScored', () => {
  it('scores TypeScript source in the package', () => {
    expect(isScored('apps/web/src/features/a.ts', 'apps/web')).toBe(true);
    expect(isScored('apps/web/src/features/a.tsx', 'apps/web')).toBe(true);
  });

  it('leaves out other packages, other languages, tests, declarations and configs', () => {
    expect(isScored('packages/sdk/src/a.ts', 'apps/web')).toBe(false);
    expect(isScored('apps/webby/src/a.ts', 'apps/web')).toBe(false);
    expect(isScored('apps/web/src/a.js', 'apps/web')).toBe(false);
    expect(isScored('apps/web/src/a.test.ts', 'apps/web')).toBe(false);
    expect(isScored('apps/web/src/a.spec.tsx', 'apps/web')).toBe(false);
    expect(isScored('apps/web/src/a.d.ts', 'apps/web')).toBe(false);
    expect(isScored('apps/web/vitest.config.ts', 'apps/web')).toBe(false);
  });

  it('leaves out test, generated and third-party folders', () => {
    expect(isScored('apps/web/src/__tests__/a.ts', 'apps/web')).toBe(false);
    expect(isScored('apps/web/tests/e2e/a.ts', 'apps/web')).toBe(false);
    expect(isScored('apps/web/src/x/browser-test/a.ts', 'apps/web')).toBe(
      false
    );
    expect(isScored('apps/web/src/generated/a.ts', 'apps/web')).toBe(false);
  });
});

describe('isGenerated', () => {
  it('finds the marker near the top only', () => {
    expect(isGenerated('// @generated by codegen\nexport {};\n')).toBe(true);
    expect(isGenerated('1\n2\n3\n4\n5\n// @generated\n')).toBe(false);
  });
});

describe('testFolders', () => {
  it('runs the tests of each touched file feature, three folders deep', () => {
    expect(
      testFolders([
        'src/features/runs/view/row.tsx',
        'src/features/runs/run.ts',
        'src/lib/a.ts',
      ])
    ).toEqual(['src/features/runs', 'src/lib']);
  });

  it('leaves out a folder inside another one', () => {
    expect(testFolders(['src/a.ts', 'src/features/runs/run.ts'])).toEqual([
      'src',
    ]);
  });

  it('runs every test for a file at the package root', () => {
    expect(testFolders(['index.ts', 'src/a.ts'])).toEqual([]);
  });
});
